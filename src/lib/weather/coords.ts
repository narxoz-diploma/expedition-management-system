/**
 * Разбор координат точки маршрута из того, что лидер вставит в одно поле.
 *
 * Почему одно текстовое поле, а не два числовых: лидер стоит с телефоном,
 * долго жмёт на точку в Google Maps и получает готовое «43.12345, 76.98765».
 * Два поля заставили бы его разрезать эту строку руками прямо в форме.
 *
 * Модуль намеренно без импортов приложения: `node --test` не понимает алиас
 * `@/`, и всё, что должно быть покрыто тестами, живёт отдельно от Next.
 */

export type RoutePoint = { lat: number; lon: number };

/**
 * Пара чисел через запятую, точку с запятой или пробел.
 *
 * Десятичный разделитель — только точка. Запятая занята под разделитель пары,
 * и «43,12345, 76,98765» разобрать однозначно нельзя: то ли это две координаты
 * с запятой внутри, то ли четыре числа. Карты отдают точку в любой локали,
 * так что терять тут нечего.
 */
const PAIR = /^(-?\d{1,3}(?:\.\d+)?)\s*[,;\s]\s*(-?\d{1,3}(?:\.\d+)?)$/;

/** Пин в ссылке Google Maps: !3d — широта, !4d — долгота. */
const GOOGLE_PIN = /!3d(-?\d+(?:\.\d+)?)!4d(-?\d+(?:\.\d+)?)/;

/** Центр карты в ссылке Google Maps: /@широта,долгота,зум. */
const GOOGLE_CENTER = /@(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/;

/**
 * Координаты из строки — или null, если разобрать не удалось.
 *
 * Ссылки 2ГИС намеренно НЕ поддерживаются, хотя в форме ссылки на карту
 * стоит подсказка про 2ГИС. В их адресах координаты идут в порядке
 * «долгота, широта» — обратном привычному. Для Алматы (43.2, 76.9) обе
 * величины правдоподобны как широта и как долгота, поэтому перепутанный
 * порядок ничем не отличить: прогноз просто придёт для точки в Ираке, и
 * никакая проверка диапазона этого не увидит. Лучше не понять ссылку, чем
 * молча понять её наоборот.
 */
export function parseRoutePoint(raw: string): RoutePoint | null {
  const text = raw.trim();
  if (text === "") return null;

  const fromUrl = text.match(GOOGLE_PIN) ?? text.match(GOOGLE_CENTER);
  const match = fromUrl ?? text.match(PAIR);
  if (!match) return null;

  const lat = Number(match[1]);
  const lon = Number(match[2]);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  if (lat < -90 || lat > 90) return null;
  if (lon < -180 || lon > 180) return null;

  // Ровные нули — это Гвинейский залив, а не маршрут: верный признак того,
  // что в поле попало не то, а не что кто-то идёт в Атлантику.
  if (lat === 0 && lon === 0) return null;

  return { lat, lon };
}

/**
 * Короткая ссылка «Поделиться» из Google Maps — самый частый способ отдать
 * место с телефона и при этом единственный, из которого координат не достать.
 *
 * Проверено вживую: `maps.app.goo.gl/…` редиректит на адрес вида
 * `/maps/place/Kok-Zhaylyau,+Almaty/data=!4m2!3m1!1s0x388364b6…`, где вместо
 * координат стоит идентификатор места. Перейти по редиректу и разобрать
 * результат не помогает — числа там не появляются ни в каком виде, их отдаёт
 * только Places API, а это ключ в окружении и регистрация в Google Cloud.
 *
 * Поэтому такую ссылку не разбираем, а узнаём — чтобы вместо общего «не
 * похоже на координаты» сказать лидеру, какой жест даёт нужные числа.
 */
export function isShortMapLink(raw: string): boolean {
  return /(maps\.app\.goo\.gl|goo\.gl\/maps)/i.test(raw);
}

/** Обратно в строку — тем же видом, в каком поле её принимает. */
export function formatRoutePoint(point: RoutePoint): string {
  return `${point.lat}, ${point.lon}`;
}
