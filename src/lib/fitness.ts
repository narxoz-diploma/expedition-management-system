/**
 * Самооценка физической формы.
 *
 * Три ступени, а не пять и не «низкий — средний — высокий»: на абстрактной
 * шкале все выбирают середину. Формулировки — через знакомую нагрузку, чтобы
 * человек сравнивал себя с делом, а не с соседом.
 *
 * Поле информационное и допуском не является. Оно отвечает на вопрос, на
 * который не отвечают ни опыт, ни снаряжение: можно бегать полумарафон и ни
 * разу не быть в горах, а можно исходить окрестности пешком и не пробежать
 * километра.
 *
 * Модуль без импортов приложения: подписи нужны и форме, и ростеру, и
 * выгрузке.
 */

export const FITNESS_LEVELS = [
  { value: 1, label: "Быстро устаю, длинных прогулок давно не было" },
  { value: 2, label: "Пройду 10 км по холмам — устану, но дойду" },
  { value: 3, label: "Регулярно хожу или бегаю, 15–20 км не проблема" },
] as const;

/** Коротко — для строки в составе группы, где места на фразу нет. */
const SHORT: Record<number, string> = {
  1: "быстро устаёт",
  2: "10 км по холмам",
  3: "ходит или бегает регулярно",
};

export function fitnessShort(level: number | null): string | null {
  return level === null ? null : (SHORT[level] ?? null);
}
