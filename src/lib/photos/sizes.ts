/**
 * Габариты и качество снимков.
 *
 * Модуль без импортов приложения и без браузерных вызовов: `node --test` не
 * понимает алиас `@/`, а `canvas` в нём не живёт вовсе. Вся арифметика,
 * которую стоит проверять, — здесь; работа с пикселями — в `resize.ts`.
 */

/** Длинная сторона снимка для просмотра. */
export const FULL_MAX_PX = 2000;

/** Длинная сторона миниатюры: сетка альбома и галерея на лендинге. */
export const THUMB_MAX_PX = 600;

/**
 * Сторона аватара.
 *
 * 512, а не 256: в шапке он кружком в несколько десятков пикселей, но на
 * лендинге в блоке «Кто ведёт» — крупной карточкой, и портреты лидеров это
 * то же самое поле. На 256 карточка была бы мылом.
 */
export const AVATAR_PX = 640;

/**
 * Качество JPEG.
 *
 * 0,82 — та точка, где на фотографии гор артефактов ещё не видно, а вес уже
 * втрое меньше исходного. Выше 0,9 файл растёт вдвое без заметной разницы.
 */
export const JPEG_QUALITY = 0.82;

/**
 * У аватара качество выше: это лицо, притом крупным планом и в кружке
 * размером с ноготь — артефакты на нём заметны там, где на горном пейзаже
 * не видны вовсе. Разница в весе — десятки килобайт на человека.
 */
export const AVATAR_QUALITY = 0.9;

/**
 * Вписывает кадр в квадрат со стороной `max`, сохраняя пропорции.
 *
 * Маленькие снимки НЕ растягиваются: увеличенный до 2000 px кадр с телефона
 * 2015 года станет мыльным и втрое тяжелее, не добавив ни одной детали.
 */
export function fitWithin(
  width: number,
  height: number,
  max: number,
): { width: number; height: number } {
  const longest = Math.max(width, height);
  if (longest <= max) return { width, height };

  const scale = max / longest;
  // Округляем вверх: 1 px в меньшую сторону при делении даёт чёрную кромку
  // на краю холста.
  return {
    width: Math.max(1, Math.ceil(width * scale)),
    height: Math.max(1, Math.ceil(height * scale)),
  };
}

/**
 * Ниже этой ширины снимок не годится в обложку.
 *
 * Карточка похода занимает почти всю ширину экрана — до 720px на десктопе, и
 * это без учёта плотности пикселей. Кадр в 240px, растянутый на такую
 * ширину, размыт до неузнаваемости, и кадрированием это не лечится: из
 * двухсот сорока пикселей информацию не достать.
 *
 * Порог взят с запасом вниз: 1200px хватает и на телефон с тройной
 * плотностью, и на десктоп, а ругаться на всё подряд вреднее, чем пропустить
 * пограничный случай.
 *
 * Откуда берутся мелкие снимки: мессенджеры сжимают фотографии при обычной
 * отправке, и сохранённая из чата копия — это уже не оригинал. Полный кадр
 * остаётся, только если файл отправляли без сжатия.
 */
export const MIN_COVER_PX = 1200;

/** Годится ли снимок в обложку, или только в плитку галереи. */
export function isTooSmallForCover(width: number): boolean {
  return width < MIN_COVER_PX;
}

/**
 * Промежуточные размеры для уменьшения в несколько шагов.
 *
 * Одним `drawImage` из 3000 px сразу в 640 браузер уменьшает билинейной
 * интерполяцией: он берёт четыре соседних пикселя из двадцати трёх, которые
 * должны были попасть в результат, и остальные просто выбрасывает. На
 * пейзаже это заметно мало, на лице — то самое мыло.
 *
 * Уменьшение вдвое браузер отрабатывает точно, поэтому половиним, пока не
 * подойдём к цели ближе чем вдвое, и только последний шаг делаем прямым.
 * Сумма получается близка к тому, что делает фоторедактор, ценой двух-трёх
 * лишних отрисовок — миллисекунды.
 *
 * Возвращает только промежуточные размеры, без исходного и без конечного:
 * их вызывающий знает и так.
 */
export function downscaleSteps(
  width: number,
  height: number,
  targetWidth: number,
  targetHeight: number,
): { width: number; height: number }[] {
  const steps: { width: number; height: number }[] = [];
  let w = width;
  let h = height;

  // Пока половина ещё не мельче цели — половиним.
  while (w / 2 >= targetWidth && h / 2 >= targetHeight) {
    w = Math.floor(w / 2);
    h = Math.floor(h / 2);
    // Ровно цель промежуточным шагом не считаем: её нарисует последний.
    if (w === targetWidth && h === targetHeight) break;
    steps.push({ width: w, height: h });
  }

  return steps;
}

/**
 * Квадрат по центру кадра — для аватара.
 *
 * По центру, а не сверху: селфи с телефона вертикальные, и верхний квадрат
 * срезал бы подбородок, оставив полкадра неба. Центр промахивается реже
 * всего, а рамки выбора области — это отдельный компонент с перетаскиванием
 * и щипком, ради поля, которое человек трогает раз в год.
 */
export function centerSquare(
  width: number,
  height: number,
): { x: number; y: number; size: number } {
  const size = Math.min(width, height);
  return {
    x: Math.round((width - size) / 2),
    y: Math.round((height - size) / 2),
    size,
  };
}
