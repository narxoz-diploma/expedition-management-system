/**
 * Метки кэша лендинга.
 *
 * Лендинг — единственная страница, которую видит толпа сразу: ссылку кидают
 * в группу, и двести человек открывают её в одну минуту. Четыре запроса из
 * восьми там у всех одинаковые, поэтому считаются один раз на всех, а не
 * заново на каждого.
 *
 * Метки лежат отдельным модулем, чтобы сбрасывающая сторона не набирала
 * строку руками: опечатка в `revalidateTag` не ломает ни сборку, ни тесты —
 * она просто ничего не сбрасывает, и расхождение всплывёт через неделю
 * жалобой «поменял фото, а на главной старое».
 *
 * Метки здесь только на то, что правится действиями в приложении. Блок «кто
 * ведёт» кэша не имеет вовсе, и метки у него нет: `club_title` и
 * `team_order` заполняются руками в SQL, то есть сбрасывать метку было бы
 * некому. Разбор — в комментарии к loadPublicLeaders.
 *
 * Сбрасывать метку из server action — это updateTag(tag), а не
 * revalidateTag(tag). В Next 16 у revalidateTag появился второй, обязательный
 * аргумент со сроками, а read-your-own-writes даёт именно updateTag: лидер
 * должен увидеть свою правку сразу, а не через минуту. По памяти напишешь
 * старый однорукий revalidateTag — не соберётся.
 */

