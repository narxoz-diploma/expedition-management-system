import { createClient as createSupabaseClient } from "@supabase/supabase-js";

import { supabasePublishableKey, supabaseUrl } from "./env";

/**
 * Клиент Supabase без сессии — для публичных данных, одинаковых у всех.
 *
 * Зачем отдельно от `createClient()`: тот читает куки, а всё, что читает
 * куки, Next считает динамическим и внутрь `unstable_cache` не пускает
 * вовсе. Кэшировать запрос, зависящий от того, кто спрашивает, и нельзя:
 * одна запись в кэше — один ответ на всех.
 *
 * Отсюда правило: сюда ходят только за тем, что политики отдают роли `anon`.
 * Сейчас это витрины `public_club_stats`, `public_leaders` и снимки
 * опубликованных походов — то, из чего собран лендинг для гостя. Если запрос
 * должен показать что-то своё, ему место в `createClient()`.
 *
 * Модульной переменной клиент не делаем по той же причине, что и там: пусть
 * это и анонимный клиент, привычка держать его в модуле однажды приведёт
 * сюда клиент с чужой сессией.
 */
export function createPublicClient() {
  return createSupabaseClient(supabaseUrl(), supabasePublishableKey(), {
    auth: {
      // Ни сессии, ни её обновления: клиент живёт один запрос и токена не
      // имеет вовсе. Без этого библиотека заводит фоновый таймер обновления,
      // бесполезный в serverless и мешающий функции завершиться.
      persistSession: false,
      autoRefreshToken: false,
    },
  });
}
