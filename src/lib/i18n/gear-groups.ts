import type { Dictionary } from "./dictionary";

/**
 * Подписи групп справочника по значению category в базе.
 *
 * Категории в gear_items хранятся русскими словами, как их завели в первой
 * миграции. Перевод — по этим словам; незнакомая группа, заведённая руками в
 * SQL, показывается как есть.
 *
 * Общее для «Моего снаряжения» и «Что взять с собой»: до 15 сентября 2026
 * жило в первой, и вторая печатала группы русскими словами на любом языке.
 */
export function gearGroupTitles(t: Dictionary["gearGroups"]): Record<string, string> {
  return {
    обувь: t.shoes,
    одежда: t.clothing,
    снаряжение: t.gear,
    безопасность: t.safety,
    прочее: t.other,
  };
}
