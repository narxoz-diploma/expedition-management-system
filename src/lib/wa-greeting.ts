/**
 * Личное приглашение в WhatsApp — вместо массового «Добавить участников».
 *
 * WhatsApp блокирует на несколько часов именно массовое добавление в
 * группу — так и устроена сборка чата, см. lib/hikes/chat-roster.ts. Но
 * личные сообщения одному номеру за другим ловятся тем же детектором
 * рассылок, если текст побайтово одинаковый: подряд полсотни копий одной
 * строки незнакомым номерам — классический признак спама. Имя в начале —
 * не про вежливость, а про то, чтобы сообщения не совпадали.
 *
 * Ссылку на группу текст несёт, только когда она заранее известна и не
 * меняется, — как у общего чата клуба (см. CLUB_CHAT_INVITE_URL). У чата
 * похода такой ссылки нет: группу под конкретный поход лидер заводит заново
 * каждый раз, сайт не может знать её вперёд, и текст обрывается на месте,
 * куда вставить её руками. В обоих случаях открывшийся черновик лидер
 * отправляет сам — ничего не уходит без его нажатия.
 */

/**
 * Приглашение в общий чат клуба — одна ссылка на всех, не на поход.
 *
 * Вписана 3 сентября 2026. Если WhatsApp когда-нибудь сбросит ссылку
 * (новую группу завели или админ группы сгенерировал новую) — старые
 * приглашения продолжат вести на неё же, пока не поправить эту константу.
 */
export const CLUB_CHAT_INVITE_URL = "https://chat.whatsapp.com/B8xkMzgfx9GEII1iOQAnUA";

/**
 * Первое слово полного имени.
 *
 * Профиль просит «Имя и фамилию» одним полем, без разбора — значит первое
 * слово чаще всего и есть имя. Точности это не гарантирует: кто-то мог
 * вписать не то, что ожидалось. Не страшно — черновик лидер видит в самом
 * WhatsApp до отправки и может поправить рукой, а не отправлять вслепую.
 */
export function firstName(fullName: string): string {
  return fullName.trim().split(/\s+/)[0] ?? "";
}

export function waInviteUrl(
  phone: string,
  fullName: string,
  /** Известная заранее ссылка на группу — не задавать, если её нет (чат похода). */
  inviteLink?: string,
): string {
  const digits = phone.replace(/\D/g, "");
  const name = firstName(fullName);
  const opener = name
    ? `Привет, ${name}! Это Step Up — вот ссылка в чат:`
    : "Привет! Это Step Up — вот ссылка в чат:";
  const greeting = inviteLink ? `${opener} ${inviteLink}` : `${opener} `;

  return `https://wa.me/${digits}?text=${encodeURIComponent(greeting)}`;
}

/**
 * «Освободилось место — идёшь?» человеку из очереди.
 *
 * После закрытия записи очередь сама не двигается: лидер спрашивает, и
 * берёт только того, кто ответил «да». Имя в начале — по той же причине,
 * что и в приглашениях: одинаковые сообщения подряд WhatsApp считает
 * рассылкой.
 */
export function waSpotOfferUrl(
  phone: string,
  fullName: string,
  hike: { title: string; dateLabel: string },
): string {
  const digits = phone.replace(/\D/g, "");
  const name = firstName(fullName);
  const hello = name ? `Привет, ${name}!` : "Привет!";
  const text = `${hello} Это Step Up — освободилось место на «${hike.title}», ${hike.dateLabel}. Идёшь? Если да — возьму тебя в группу.`;
  return `https://wa.me/${digits}?text=${encodeURIComponent(text)}`;
}
