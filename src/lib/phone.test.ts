import { describe, it } from "node:test";
import assert from "node:assert/strict";

import { formatPhone, normalizePhone } from "./phone.ts";

describe("нормализация телефона", () => {
  it("приводит к одному виду всё, как люди реально пишут", () => {
    const same = [
      "+77012345678",
      "87012345678",
      "8 701 234 56 78",
      "+7 (701) 234-56-78",
      "7012345678",
      "  +7-701-234-5678  ",
    ];
    for (const input of same) {
      assert.equal(
        normalizePhone(input),
        "+77012345678",
        `не сошлось на «${input}»`,
      );
    }
  });

  it("принимает разные мобильные коды", () => {
    assert.equal(normalizePhone("+77471112233"), "+77471112233");
    assert.equal(normalizePhone("+77751112233"), "+77751112233");
  });

  it("отказывается от того, что телефоном не является", () => {
    for (const bad of ["", "не телефон", "123", "+7701234567"]) {
      assert.equal(normalizePhone(bad), null, `принял «${bad}»`);
    }
  });

  it("буква среди цифр — это не разделитель", () => {
    // Раньше такое отсеивалось случайно: букву выбрасывали вместе с прочими
    // не-цифрами, а остаток не проходил казахстанскую маску. С российскими
    // номерами остаток стал валидным, и проверка понадобилась явная.
    assert.equal(normalizePhone("+79012345678x"), null);
    assert.equal(normalizePhone("+7701234о678"), null);
  });

  it("не принимает городской номер вместо мобильного", () => {
    // 727 — код Алматы, WhatsApp на нём не работает.
    assert.equal(normalizePhone("+77272345678"), null);
  });

  it("принимает иностранный номер с кодом страны", () => {
    // Индонезийский код — на таком номере это и вскрылось 29 августа 2026:
    // тем же валидатором проверяется телефон в профиле и контакт на случай
    // ЧП, так что человек не мог ни записаться в поход, ни вписать родителя.
    // Сам номер здесь выдуманный: настоящему не место ни в репозитории, ни
    // тем более в подсказке на экране.
    assert.equal(normalizePhone("+62 812 3456 7890"), "+6281234567890");
    assert.equal(normalizePhone("+44 20 7946 0958"), "+442079460958");
  });

  it("российский мобильный тоже проходит — код страны у нас общий", () => {
    // Разбор «плюс и цифры» его не спасает: код страны у него +7, то есть
    // номер идёт по казахстанской ветке и упирался в маску мобильных кодов.
    assert.equal(normalizePhone("+7 912 345 67 89"), "+79123456789");
    assert.equal(normalizePhone("8 912 345 67 89"), "+79123456789");
  });

  it("иностранный номер без кода страны не угадывает", () => {
    // Без плюса номер считается здешним: иностранный от местного не
    // отличить. Под казахстанский мобильный он не подойдёт и будет отклонён
    // — а это честнее, чем молча увести человека в +7.
    assert.equal(normalizePhone("8123456789"), null);
  });

  it("отбивает бессмыслицу с плюсом", () => {
    for (const bad of ["+0123456789", "+123", "+1234567890123456"]) {
      assert.equal(normalizePhone(bad), null, `принял «${bad}»`);
    }
  });

  it("показывает номер читаемо", () => {
    assert.equal(formatPhone("+77012345678"), "+7 701 234 56 78");
  });

  it("иностранный показывает как есть, а не разбивает наугад", () => {
    // Разбитый по чужим правилам номер выглядит осмысленным и врёт — это
    // хуже сплошной строки.
    assert.equal(formatPhone("+6281234567890"), "+6281234567890");
  });
});
