/**
 * Приведение телефона к одному виду: +<код страны><номер>.
 *
 * Формат важен не для красоты: номер — ключ связи с WhatsApp и уникальный
 * индекс в profiles. Лидер вставляет список номеров из группы и сверяет их с
 * профилями; если один и тот же человек записан как «8 701 …», а другой как
 * «+7 (701) …», сверка не сойдётся, а уникальный индекс пропустит дубль.
 *
 * До 29 августа 2026 принимались только казахстанские мобильные, и это
 * оказалось не мелкой строгостью, а отказом в обслуживании: тем же валидатором
 * проверяется телефон в профиле — обязательный для записи в поход — и
 * контакт на случай ЧП. Студент с индонезийским номером не мог ни записаться
 * никуда, ни вписать родителя, по которому ему будут звонить, если что-то
 * случится в горах. Сообщение при этом говорило «похоже на опечатку», хотя
 * человек не ошибся — сайт отказывал его стране.
 *
 * Возвращает null, если на телефон не похоже.
 */

/**
 * Мобильные под кодом +7. Он общий у Казахстана и России.
 *
 * Казахстан: 70x, 74x, 75x, 76x, 77x — вторая цифра отсекает городские
 * номера (727 Алматы, 717 Астана), на них WhatsApp не работает, а телефон
 * нужен именно для него.
 *
 * Россия: все мобильные начинаются с 9. Без этой половины россиянин упирался
 * бы ровно в ту же стену, что и индонезиец, — и общий разбор «+ и цифры»
 * ниже его не спасает, потому что код страны у него наш.
 */
const SEVEN_MOBILE = /^(7[04567]\d{8}|9\d{9})$/;

/**
 * Всё остальное проверяем только по форме: плюс, код страны и номер, всего
 * от 8 до 15 цифр (потолок задан E.164).
 *
 * Мобильные префиксы полутора сотен стран мы не знаем, и попытка угадывать
 * отклоняла бы настоящие номера — то есть повторяла бы ошибку, которую этот
 * код и чинит. Код страны с нуля не начинается ни у кого.
 */
const INTERNATIONAL = /^[1-9]\d{7,14}$/;

/**
 * Что человек вправе написать между цифрами: пробелы, скобки, дефисы, точки.
 * Всё остальное — не разделитель, а признак, что это не номер.
 *
 * Проверка нужна именно теперь. Раньше буква на конце отсеивалась случайно:
 * её выкидывали вместе с прочими не-цифрами, а то, что оставалось, всё равно
 * не проходило казахстанскую маску. С появлением российских и иностранных
 * номеров «+79012345678x» стал бы валидным, и мусор проехал бы в базу.
 */
const SEPARATORS_ONLY = /^[0-9 ().-]+$/;

export function normalizePhone(input: string): string | null {
  const trimmed = input.trim();

  // «Плюс» снимаем до проверки: он допустим только в начале, и так это
  // сказано без отдельного правила о его месте.
  const body = trimmed.startsWith("+") ? trimmed.slice(1) : trimmed;
  if (!SEPARATORS_ONLY.test(body)) return null;

  const digits = trimmed.replace(/\D/g, "");
  if (digits.length === 0) return null;

  if (trimmed.startsWith("+")) {
    // Код страны указан явно.
    if (digits.startsWith("7")) {
      // Наш код — значит дальше обязаны идти ровно 10 цифр. Проверять это
      // надо до отбрасывания «+»: без него «+7701234567» (на цифру короче)
      // неотличим от полного номера без кода страны и молча превращается в
      // чужой номер.
      if (digits.length !== 11) return null;
      const national = digits.slice(1);
      return SEVEN_MOBILE.test(national) ? `+7${national}` : null;
    }
    return INTERNATIONAL.test(digits) ? `+${digits}` : null;
  }

  // Без «плюса» считаем номер здешним: иностранный без кода страны от
  // местного не отличить, и «812 3456 7890» ушло бы в +7 чужим номером.
  let national: string;
  if (digits.length === 11 && (digits.startsWith("7") || digits.startsWith("8"))) {
    // 8XXXXXXXXXX — привычная запись внутри страны, и в Казахстане, и в России
    national = digits.slice(1);
  } else if (digits.length === 10) {
    // XXXXXXXXXX — набрали без кода страны
    national = digits;
  } else {
    return null;
  }

  return SEVEN_MOBILE.test(national) ? `+7${national}` : null;
}

/**
 * «+7 701 234 56 78» — для показа, не для хранения.
 *
 * Разбивку знаем только для своего кода. Иностранный номер возвращается как
 * есть: чтобы разбить его правильно, нужны правила его страны, а разбитый
 * наугад читается хуже сплошного — он выглядит осмысленным и врёт.
 */
export function formatPhone(phone: string): string {
  const match = phone.match(/^\+7(\d{3})(\d{3})(\d{2})(\d{2})$/);
  if (!match) return phone;
  return `+7 ${match[1]} ${match[2]} ${match[3]} ${match[4]}`;
}
