// Запуск: npm run test:unit
//
// Первый пример — настоящее описание с прода, по нему правило и писалось.
// Важнее всего тут случаи «не резать»: ошибка в эту сторону показывает
// разрезанное предложение как маршрут, и выглядит это хуже абзаца.

import { describe, it } from "node:test";
import assert from "node:assert/strict";

import { parseRouteDescription } from "./route-steps.ts";

const REAL =
  'Алма-Арасан – Водопад "Девичьи слезы" – Лесная зона и подъем по ущелью – Русло высохшей реки – Мост из труб перед финальным подъемом – Поляна Терра.';

describe("описание маршрута цепочкой", () => {
  it("настоящее описание разбирается на шесть точек", () => {
    assert.deepEqual(parseRouteDescription(REAL), {
      steps: [
        "Алма-Арасан",
        'Водопад "Девичьи слезы"',
        "Лесная зона и подъем по ущелью",
        "Русло высохшей реки",
        "Мост из труб перед финальным подъемом",
        "Поляна Терра",
      ],
      rest: null,
    });
  });

  it("подпись «Маршрут:» перед цепочкой не становится частью первой точки", () => {
    // Так начинались четыре описания из шести на проде.
    assert.deepEqual(parseRouteDescription("Маршрут: Медео – Горельник – Медео").steps, [
      "Медео",
      "Горельник",
      "Медео",
    ]);
    assert.equal(parseRouteDescription("маршрут:Медео – Горельник – Медео").steps?.[0], "Медео");
  });

  it("в абзаце подпись «Маршрут:» остаётся как написана", () => {
    const text = "Маршрут: от Медеу вверх по тропе к Горельнику и обратно.";
    assert.deepEqual(parseRouteDescription(text), { steps: null, rest: text });
  });

  it("дефис внутри названия не режет, в пробелах — режет", () => {
    assert.deepEqual(parseRouteDescription("Кок-Жайляу - Букреева - Пик Фурманова").steps, [
      "Кок-Жайляу",
      "Букреева",
      "Пик Фурманова",
    ]);
  });

  it("длинное тире, двойной дефис и стрелка — тоже разделители", () => {
    assert.deepEqual(parseRouteDescription("Медеу — Шымбулак -- Талгарский перевал → Пик").steps, [
      "Медеу",
      "Шымбулак",
      "Талгарский перевал",
      "Пик",
    ]);
  });

  it("перенос строки внутри цепочки её не ломает", () => {
    assert.deepEqual(parseRouteDescription("Медеу –\nШымбулак –\nТалгарский перевал").steps, [
      "Медеу",
      "Шымбулак",
      "Талгарский перевал",
    ]);
  });

  it("абзац после цепочки остаётся текстом под схемой", () => {
    const result = parseRouteDescription(`${REAL}\n\nВоду брать с собой, родников нет.`);
    assert.equal(result.steps?.length, 6);
    assert.equal(result.rest, "Воду брать с собой, родников нет.");
  });

  it("рассказ остаётся абзацем целиком", () => {
    const story =
      "Идём от Медеу вверх по тропе — сначала лесом, потом по гребню. Там отдых и обратно тем же путём.";
    assert.deepEqual(parseRouteDescription(story), { steps: null, rest: story });
  });

  it("две точки — не схема", () => {
    assert.equal(parseRouteDescription("Медеу – Шымбулак").steps, null);
  });

  it("часть с предложением внутри делает всё абзацем", () => {
    const text = "Медеу – Шымбулак. Там обед и отдых – Талгарский перевал – Пик";
    assert.equal(parseRouteDescription(text).steps, null);
  });

  it("пустая часть (два тире подряд) — не цепочка", () => {
    assert.equal(parseRouteDescription("Медеу – – Шымбулак – Пик").steps, null);
  });

  it("пустое описание — ни схемы, ни текста", () => {
    assert.deepEqual(parseRouteDescription("   "), { steps: null, rest: null });
  });
});
