/**
 * Когда открываются отметки явки.
 *
 * Правило живёт в базе — `mark_attendance()` отвечает `HIKE_NOT_STARTED`, —
 * а здесь его копия для интерфейса. Дублирование намеренное и того же рода,
 * что у `closedReason()` на карточке похода: решение принимает база, но
 * человеку надо показать неактивные кнопки и причину до нажатия, а не после.
 * Меняя число, менять в обоих местах.
 *
 * Модуль без импортов приложения — его гоняет `node --test`.
 */

/**
 * Запас до выхода, в течение которого отмечать уже можно.
 *
 * Два часа, потому что лидер отмечает пришедших на точке сбора, то есть до
 * старта, а сбор назначают за час-полтора. С меньшим запасом кнопки были бы
 * заблокированы ровно в тот момент, когда они нужны.
 */
export const MARK_OPENS_BEFORE_MS = 2 * 60 * 60 * 1000;

/** Момент, с которого лидер может отмечать явку. */
export function attendanceOpensAt(startsAt: string): string {
  return new Date(
    new Date(startsAt).getTime() - MARK_OPENS_BEFORE_MS,
  ).toISOString();
}

/**
 * Можно ли уже отмечать.
 *
 * Верхней границы нет: поход прошёл неделю назад, а лидер добрался до
 * телефона только сейчас — обычное дело, и запрещать тут нечего.
 */
export function canMarkAttendance(startsAt: string, now: Date): boolean {
  return now.getTime() >= new Date(attendanceOpensAt(startsAt)).getTime();
}
