/**
 * Описание маршрута цепочкой точек → список точек.
 *
 * Лидеры и так пишут маршрут цепочкой: «Алма-Арасан – Водопад „Девичьи слёзы“
 * – Лесная зона – … – Поляна Терра». Строкой такое читается как сплошной серый
 * абзац, а столбиком — как маршрут (просьба автора, 15 сентября 2026). Нового
 * поля под точки нет намеренно: лидер пишет как писал, сайт узнаёт цепочку сам.
 *
 * Узнаёт осторожно. Цепочкой считается только первый абзац, в котором не
 * меньше трёх коротких частей и ни одна не похожа на предложение. Всё прочее
 * остаётся текстом как есть: угадывать точки в рассказе — значит однажды
 * разрезать предложение посередине и показать это как маршрут.
 *
 * Модуль без импортов приложения: его гоняет node --test.
 */

export type RouteDescription = {
  /** Точки по порядку, или null — описание не цепочка. */
  steps: string[] | null;
  /** Текст, который остаётся абзацем: всё описание или хвост под цепочкой. */
  rest: string | null;
};

/** Меньше трёх — это «откуда — куда», схема из двух точек ничего не добавляет. */
const MIN_STEPS = 3;

/** Длиннее — уже не название места, а фраза. */
const MAX_STEP_LENGTH = 80;

/*
 * Разделители: тире обоих видов, двойной дефис и стрелка — с пробелами или без,
 * а одиночный дефис только в пробелах. Без пробелов дефис живёт внутри названий
 * («Алма-Арасан», «Кок-Жайляу»), и резать по нему нельзя.
 */
const SEPARATOR = /\s*(?:→|—|–|--)\s*|\s+-\s+/;

/*
 * Похоже на предложение: знак конца предложения с продолжением после него.
 * Точка в самом конце последней части — не предложение, её лидер ставит
 * по привычке, и она снимается.
 */
const SENTENCE_BREAK = /[.!?…]\s+\S/;

/*
 * Подпись перед цепочкой. На проде четыре описания из шести начинались с
 * «Маршрут: Медео – …», и первой точкой выходило «Маршрут: Медео» — под
 * заголовком «О маршруте» это слово лишнее и читается как часть названия.
 * Снимается только у цепочки: в абзаце текст остаётся как написан.
 */
const ROUTE_LABEL = /^маршрут\s*:\s*/i;

export function parseRouteDescription(description: string): RouteDescription {
  const text = description.trim();
  if (text === "") return { steps: null, rest: null };

  const [first, ...others] = text.split(/\n\s*\n/);
  const rest = others.join("\n\n").trim() || null;

  // Цепочку иногда переносят на новую строку посередине — это всё ещё она.
  const parts = first
    .replace(/\s*\n\s*/g, " ")
    .replace(ROUTE_LABEL, "")
    .split(SEPARATOR)
    .map((part) => part.trim());

  const last = parts.length - 1;
  if (last >= 0) parts[last] = parts[last].replace(/[.;]+$/, "").trim();

  const isChain =
    parts.length >= MIN_STEPS &&
    parts.every(
      (part) =>
        part !== "" && part.length <= MAX_STEP_LENGTH && !SENTENCE_BREAK.test(part),
    );

  if (!isChain) return { steps: null, rest: text };
  return { steps: parts, rest };
}
