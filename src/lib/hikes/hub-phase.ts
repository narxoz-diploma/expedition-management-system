/**
 * Фаза экрана группы: что лидеру делать с походом прямо сейчас.
 *
 * Экран группы до 14 сентября 2026 был одинаковым у черновика, набора, дня
 * выхода и прошедшего похода: анонс, выгрузка, чат, явка, состав, фото и
 * отмена — всегда все и в одном порядке. У прошедшего оставались «Снять с
 * похода» и плашка про согласие родителей, у будущего — загрузка фото.
 * Решение автора — экран полностью по фазам: наверху дело текущей фазы,
 * остального в ней нет.
 *
 * Порядок веток — вся логика модуля, и держится он тестами, как и
 * `registration-cta.ts`: порядок, который помнят головой, ломается при первой
 * правке вёрстки.
 *
 * Модуль без импортов приложения — его гоняет `node --test`. Сосед берётся
 * относительным путём с расширением: алиас `@/` тест не понимает.
 */

import { GATHERING_GRACE_MS } from "./attendance-progress.ts";
import { cancellationCutoff } from "./cancel-cutoff.ts";

export type HubPhase =
  /** Участники не видят. Дело — опубликовать или удалить. */
  | "draft"
  /** Опубликован, до выхода больше полусуток. Дело — звать людей. */
  | "recruiting"
  /** Запись закрыта, выход впереди. Дело — список, чат, явка на сборе. */
  | "departure"
  /** Сбор позади. Дело — итог и фотографии. */
  | "outcome"
  /** Отменён. Дело — сказать группе. */
  | "cancelled";


export function hubPhase(
  hike: {
    status: "draft" | "published" | "cancelled" | "completed";
    startsAt: string;
    registrationClosesAt: string | null;
  },
  now: Date,
): HubPhase {
  // Отмена важнее всего: отменённый поход и в прошлом, и в будущем — это
  // объявление группе, а не итог и не набор.
  if (hike.status === "cancelled") return "cancelled";
  // Черновик остаётся черновиком и после даты: его никто не видел, итога у
  // него нет.
  if (hike.status === "draft") return "draft";
  if (hike.status === "completed") return "outcome";

  const start = new Date(hike.startsAt).getTime();
  // Не ровно по старту, а когда кончается сбор на экране явки: иначе в
  // первые два часа после выхода экран группы звал бы к итогам, а экран
  // явки — отмечать опоздавших.
  if (now.getTime() >= start + GATHERING_GRACE_MS) return "outcome";
  // День выхода начинается с рубежа отмены — закрытия записи, иначе за
  // сутки до выхода: с этого момента состав почти не меняется, и лидеру
  // нужен список и чат, а не анонс, зовущий новых людей. До 21 сентября
  // 2026 это были 12 часов — та же граница, что у поздней отмены тогда.
  if (now.getTime() >= new Date(cancellationCutoff(hike)).getTime()) return "departure";
  return "recruiting";
}
