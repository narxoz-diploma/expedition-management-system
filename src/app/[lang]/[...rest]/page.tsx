import { notFound } from "next/navigation";

/**
 * Любой адрес, которого нет, — в нашу 404.
 *
 * Корневой layout лежит под динамическим сегментом [lang], и общей 404 на
 * «адрес не совпал ни с чем» у такой раскладки нет: Next показал бы свою,
 * белую и английскую (документация not-found, раздел про global-not-found).
 * Страница-ловушка переводит несовпавший адрес в обычный notFound(), и его
 * ловит [lang]/not-found.tsx — с шапкой, подвалом и темой.
 *
 * Более конкретные маршруты всегда побеждают catch-all, так что сюда
 * попадает только то, чего действительно нет.
 */
export default function CatchAll() {
  notFound();
}
