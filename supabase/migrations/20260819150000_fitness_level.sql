-- Физическая подготовка в профиле.
--
-- ============================================================
-- ЗАЧЕМ И ПОЧЕМУ НЕ ВОРОТА
--
-- Поле информационное. Ворот по нему не будет: самооценка даёт человеку ключ
-- от собственной двери, и ошибаются в обе стороны — один запишется на
-- пятёрку, другой побоится идти на прогулку.
--
-- Оно отвечает на вопрос, на который не отвечает ни опыт, ни снаряжение:
-- можно бегать полумарафон и ни разу не быть в горах, а можно исходить все
-- окрестности пешком и не пробежать километра. Лидеру это разные люди, и в
-- составе группы поле стоит рядом с «где уже был».
--
-- Три ступени, а не пять и не «низкий — средний — высокий»: на абстрактной
-- шкале все выбирают середину. Формулировки — через знакомую нагрузку,
-- чтобы человек сравнивал себя с делом, а не с соседом.
-- ============================================================

alter table profiles
  add column fitness_level smallint;

alter table profiles
  add constraint profiles_fitness_level_range
  check (fitness_level is null or fitness_level between 1 and 3);

comment on column profiles.fitness_level is
  '1 — быстро устаю; 2 — пройду 10 км по холмам; 3 — регулярно хожу или бегаю. Информационное, не допуск.';

-- ============================================================
-- ОБЯЗАТЕЛЬНОЕ ПОЛЕ
--
-- Иначе заполнит половина, и лидер не отличит «слабый» от «не ответил» —
-- а это, как и с снаряжением, разные действия: одному написать, у другого
-- спросить.
--
-- Цена: у новичка в мини-профиле становится на одно поле больше ровно в тот
-- момент, когда он торопится записаться. Взвешено сознательно — это три
-- варианта в один тап, а не текст, и экстренный контакт, который мы требуем
-- давно, куда муторнее.
--
-- Старые профили от этого не ломаются: запись на поход попросит дозаполнить
-- профиль тем же путём, что и раньше (PROFILE_INCOMPLETE), а всё остальное
-- на сайте продолжает работать.
-- ============================================================

create or replace function profile_is_complete(p_user uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from profiles p
    where p.id = p_user
      and p.phone is not null
      and p.birth_date is not null
      and p.consent_pd_at is not null
      and p.fitness_level is not null
      and exists (select 1 from emergency_contacts ec where ec.user_id = p.id)
  );
$$;
