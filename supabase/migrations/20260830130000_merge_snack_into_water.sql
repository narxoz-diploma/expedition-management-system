-- ============================================================
-- ПЕРЕКУС ПЕРЕЕЗЖАЕТ В СТРОКУ С ВОДОЙ
--
-- Вчерашний разбор довёл первую категорию с четырёх пунктов до шести, и на
-- экране это стало заметно: список для первого похода — то место, где новичок
-- решает, по силам ли ему клуб, и длина там работает против.
--
-- Выкидывать перекус нельзя: голод на шести часах — не мелочь, и «человек
-- просто устал и замёрз» чаще всего означает, что он не ел. Но вода и еда —
-- это один и тот же жест сборов, и разносить их по двум строкам список
-- удлиняет, а сборы не улучшает.
--
-- Строк в первой категории снова пять... точнее, пять: обувь, рюкзак,
-- дождевик, вода с перекусом, головной убор с кремом.
-- ============================================================

update gear_items
   set name = 'Вода 1,5 л и перекус'
 where slug = 'water';

-- Строка `snack` заведена вчера, в 20260830120000. Живых отметок у неё быть
-- не должно — справочник изменился накануне, — а если есть, они уедут по
-- `on delete cascade` в user_gear. Потеря здесь безобидная: человек ответил
-- «есть перекус», а теперь ответит то же самое строкой про воду.
delete from gear_items where slug = 'snack';
