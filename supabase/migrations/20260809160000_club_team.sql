-- Команда клуба на лендинге: подпись роли, порядок и инстаграм.
--
-- Подписи чисто информативные. Жёсткой иерархии в клубе нет, все в команде —
-- лидеры и по системной роли тоже; человек с подписью «SMM» ведёт походы
-- наравне с остальными. Поэтому club_title НИКАК не связан с profiles.role и
-- ни на какие права не влияет: это надпись под фотографией, не более.
alter table profiles
  add column club_title text,
  add column team_order int,
  add column instagram  text;

comment on column profiles.club_title is
  'Подпись под фото на лендинге: «Основатель», «SMM». Информативно, прав не даёт.';

-- Порядок на лендинге и одновременно признак показа.
--
-- Признак нужен: витрина public_leaders показывает всех с ролью leader или
-- admin, и на главную уже попал тестовый профиль. Отбор по «кого вписали
-- руками» отсеивает и тестовые учётки, и бывших лидеров, которым роль
-- забыли снять, — без чистки базы и без ещё одного флага.
comment on column profiles.team_order is
  'Место на лендинге. Пусто — на лендинге не показывается.';

-- Ник, а не ссылка целиком: собрать адрес мы умеем сами, а вот проверить
-- чужую ссылку — нет. Поле заполняется руками из SQL-редактора, и опечатка
-- вроде «instagram.com/username» вместо ника обнаружилась бы битой ссылкой
-- на самом видном месте.
alter table profiles
  add constraint profiles_instagram_handle
  check (instagram is null or instagram ~ '^[A-Za-z0-9._]{1,30}$');

comment on column profiles.instagram is
  'Ник без @ и без адреса. Ссылка собирается в коде.';

-- ============================================================
-- ВИТРИНА
--
-- Состав колонок public_leaders — это граница публичности, расширять её
-- просто так нельзя (см. комментарий в init.sql). Здесь расширяем осознанно:
-- подпись роли, порядок и ник в инстаграме человек публикует о себе сам, и
-- ровно для того, чтобы их видели на лендинге. Телефонов и дат рождения это
-- не касается.
--
-- Фильтр по team_order сюда НЕ добавляем: эту же витрину читает карточка
-- похода, чтобы показать, кто ведёт. Отбор для лендинга делает запрос
-- listPublicLeaders — иначе у походов пропали бы имена лидеров.
-- ============================================================

create or replace view public_leaders with (security_invoker = false) as
  select p.id, p.full_name, p.avatar_url, p.bio,
         p.club_title, p.team_order, p.instagram
  from profiles p
  where p.role in ('leader', 'admin');
