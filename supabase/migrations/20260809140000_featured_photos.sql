-- Снимок на главную — выбором, а не по дате.
--
-- Сначала герой лендинга брал обложку последнего состоявшегося похода. Это
-- экономило экран, но у героя другая работа: это единственная картинка,
-- которую увидят все, и выбирать её должен человек, а не порядок дат.
--
-- Отдельного экрана под выбор нет: отметка ставится там же, где лидер уже
-- разбирает снимки похода. Флаг, а не «id снимка для главной» в настройках
-- клуба, — потому что кадров на главной несколько, они сменяются, и список
-- в одной строке настроек пришлось бы разбирать вручную.
alter table hike_photos
  add column featured boolean not null default false;

-- Частичный индекс: отмеченных единицы на всю базу, и главная спрашивает
-- ровно их. Полный индекс по булеву столбцу в основном хранил бы false.
create index hike_photos_featured_idx
  on hike_photos (created_at desc)
  where featured;

comment on column hike_photos.featured is
  'Показывать в герое лендинга. Ставит лидер похода на своём экране.';
