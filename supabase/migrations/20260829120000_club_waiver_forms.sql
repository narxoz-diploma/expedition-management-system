-- ============================================================
-- БЛАНКИ РАСПИСКИ ПЕРЕЕЗЖАЮТ К КЛУБУ
--
-- Миграция 20260812130000 объясняла, почему файлы лежат у похода: «в бланке
-- стоят дата и название маршрута, один общий шаблон пришлось бы дозаполнять
-- руками каждому». Довод оказался неверным — выяснилось 29 августа 2026.
-- Бланк универсальный, их всего два (взрослый и детский), а название похода
-- и дату участник вписывает в него сам в любом случае. То есть прежнее
-- устройство брало с лидера две загрузки на каждый поход и не давало взамен
-- ничего.
--
-- Хуже того, оно давало сбой: плашка «нужна расписка» на странице похода и
-- строка о ней в анонсе показывались, только если файлы приложены. Лидер,
-- забывший их приложить, оставлял участника без единого упоминания о бумаге
-- — а на сборе того разворачивают. Клубные бланки этот сценарий убирают:
-- файлы загружены один раз и есть всегда.
--
-- Расписка нужна на каждый поход без исключений (решение автора, 29 августа),
-- поэтому отдельного признака «нужна ли она здесь» у похода нет: показывать
-- её надо всегда.
-- ============================================================

-- ============================================================
-- ТАБЛИЦА
--
-- Строк ровно две, и ключ — это вид бланка: у клуба не может быть двух
-- взрослых расписок. Первичный ключ по kind закрывает вопрос без отдельного
-- уникального индекса и без id, который никому не нужен.
--
-- Не enum: тип ради двух значений, живущих в одной таблице, добавил бы
-- отдельный файл миграции (новое значение enum нельзя использовать в той же
-- транзакции, где оно добавлено) и ничего бы не дал.
--
-- Название узкое намеренно. `club_documents` звучало бы шире и тем самым
-- приглашало сваливать сюда всё подряд — это таблица бланков расписки.
-- ============================================================

create table waiver_forms (
  kind        text primary key check (kind in ('adult', 'minor')),
  path        text not null,
  uploaded_by uuid references profiles(id),
  updated_at  timestamptz not null default now()
);

alter table waiver_forms enable row level security;

-- Читать может кто угодно, включая анонима. Здесь лежит путь к файлу, а не
-- сам файл: доступ к содержимому решает политика бакета. Аноним же должен
-- знать, что на поход нужна бумага, — плашка стоит на странице похода и
-- видна до записи, а ей надо отличать «бланк есть» от «бланк ещё не
-- загружен».
create policy waiver_forms_read on waiver_forms
  for select using (true);

-- Загружает любой лидер, а не только админ (решение автора, 29 августа):
-- бланк меняют раз в год, и упирать это в одного человека значит однажды
-- ждать его из отпуска.
create policy waiver_forms_write on waiver_forms
  for all to authenticated using (is_staff()) with check (is_staff());

grant select on waiver_forms to anon, authenticated;
grant insert, update, delete on waiver_forms to authenticated;

-- ============================================================
-- БАКЕТ
--
-- Закрытый, как и прежний: адрес файла из открытого бакета пересылается в
-- чат и работает вечно. Ссылки по-прежнему подписываются на минуту.
--
-- Но читать может любой вошедший, а не только участник конкретного похода.
-- Раньше политика разбирала первый сегмент пути как id похода; у клубного
-- бланка похода нет, и привязывать его к «идёт хоть куда-нибудь» значило бы
-- писать в политике то, чего она не знает. Отбор, кому показывать ссылку,
-- делает страница похода; сам бланк — пустая форма без персональных данных,
-- и вход в клуб для неё достаточная граница.
-- ============================================================

insert into storage.buckets (id, name, public)
values ('waiver-forms', 'waiver-forms', false)
on conflict (id) do nothing;

create policy waiver_forms_object_read on storage.objects
  for select to authenticated
  using (bucket_id = 'waiver-forms');

create policy waiver_forms_object_write on storage.objects
  for insert to authenticated
  with check (bucket_id = 'waiver-forms' and is_staff());

create policy waiver_forms_object_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'waiver-forms' and is_staff());
