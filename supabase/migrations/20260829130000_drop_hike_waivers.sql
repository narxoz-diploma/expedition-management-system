-- Данных в колонках нет: на проде не загружено ни одного бланка (проверено
-- автором 29 августа).
--
-- ------------------------------------------------------------
-- Почему в файле только alter table
--
-- Сначала здесь же снимались политики бакета `waivers`, и на живой базе это
-- дало `deadlock detected`. Причина в том, что одна транзакция бралась за
-- две несвязанные таблицы: политики держат `storage.objects`, а `alter table`
-- ждёт монопольную блокировку на `hikes`. Встречный процесс держал их в
-- обратном порядке — классический перехлёст.
--
-- Политики уехали в отдельный файл. Каждая миграция — своя транзакция,
-- значит теперь ни одна не держит обе таблицы сразу, и перехлёстываться
-- нечему.
--
-- ------------------------------------------------------------
-- Почему lock_timeout
--
-- `drop column` берёт AccessExclusiveLock: на время операции таблица закрыта
-- и для чтения. Сама операция мгновенная — она правит каталог, а не данные,
-- — но встать в очередь за долгим чужим запросом она может, и тогда за ней
-- выстроятся все читатели, то есть весь сайт.
--
-- Пять секунд означают «не получилось взять блокировку — отваливаемся и не
-- держим никого». Упавшую миграцию можно просто запустить снова; заблокированный
-- прод так просто не чинится.
-- ------------------------------------------------------------

set local lock_timeout = '5s';

alter table hikes
  drop column if exists waiver_adult_path,
  drop column if exists waiver_minor_path;
