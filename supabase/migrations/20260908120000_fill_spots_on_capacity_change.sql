-- ============================================================
-- РАСШИРЕНИЕ ВМЕСТИМОСТИ ПОДНИМАЕТ ЛЮДЕЙ ИЗ ОЧЕРЕДИ
--
-- Баг, найденный автором: на походе 25 мест и очередь, лидер ставит 30 — и
-- ничего не происходит. Пять мест висят свободными, пять человек продолжают
-- стоять в листе ожидания.
--
-- Причина: подъём из очереди жил только там, где место ОСВОБОЖДАЛОСЬ —
-- в cancel_registration() и в назначении лидера. Оба зовут
-- promote_from_waitlist(). Случай «мест стало больше» не освобождает ничего,
-- поэтому в него никто не заглянул, а вместимость — вторая половина того же
-- уравнения: место появляется и когда кто-то ушёл, и когда границу
-- подвинули.
--
-- Хуже, чем просто застрявшая очередь: свободные места видны на карточке и
-- достаются тому, кто нажмёт «Записаться» сейчас. place_registration()
-- сравнивает занятые с capacity и отдаёт confirmed сразу — то есть новый
-- человек проходит вперёд тех, кто уже ждал. Очередь при этом выглядит
-- работающей.
--
-- ------------------------------------------------------------
-- ПОЧЕМУ ТРИГГЕР, А НЕ ВЫЗОВ ИЗ saveHike()
--
-- Вместимость правят не только формой: у лидера есть право на UPDATE hikes
-- по политике, а anon key лежит в клиентском бандле; и сам автор регулярно
-- правит данные руками в SQL-редакторе. Правило, живущее в приложении, все
-- эти пути не видит — ровно та же беда, что была с кэшем блока «Команда»,
-- который сбрасывался только сохранением через сайт.
--
-- Место в группе — это не отображение, а обязательство перед человеком.
-- Такое обязано держаться базой, как и сама запись в поход.
--
-- ------------------------------------------------------------
-- УМЕНЬШЕНИЕ ВМЕСТИМОСТИ НИКОГО НЕ ВЫСАЖИВАЕТ
--
-- Триггер срабатывает на любое изменение capacity, но обратный ход ничего не
-- делает намеренно: fill_open_spots() при переполнении выходит сразу. Снять
-- уже подтверждённого человека — решение лидера и разговор с человеком, а не
-- следствие правки числа в форме. Счётчик свободных мест при этом не уходит
-- в минус, его обрезает spotsLeft() в приложении.
-- ============================================================

-- Поднимает столько людей, сколько влезает, а не одного.
--
-- Считать вместимость заново здесь незачем: promote_from_waitlist() уже
-- знает всё правило целиком — и что лидеры мест не занимают, и порядок
-- очереди, и пересчёт позиций. Копия этой арифметики рядом разъехалась бы с
-- оригиналом, а разъехавшись — дала бы поход, где место свободно, а очередь
-- стоит. То есть ровно то, что чиним.
create or replace function fill_open_spots(p_hike_id uuid)
returns setof uuid language plpgsql security definer set search_path = public as $$
declare
  v_promoted uuid;
begin
  -- Верхняя граница, а не while true: цикл в триггере на живой базе не имеет
  -- права зациклиться никогда, даже если promote_from_waitlist() однажды
  -- начнёт возвращать одного и того же человека. Тысяча заведомо больше
  -- любой очереди студенческого клуба.
  for i in 1..1000 loop
    v_promoted := promote_from_waitlist(p_hike_id);
    exit when v_promoted is null;
    return next v_promoted;
  end loop;
end;
$$;

revoke all on function fill_open_spots(uuid) from public, anon, authenticated;

create or replace function fill_spots_on_capacity_change()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform * from fill_open_spots(new.id);
  perform refresh_hike_counters(new.id);
  return null;
end;
$$;

revoke all on function fill_spots_on_capacity_change() from public, anon, authenticated;

-- Рекурсии нет: refresh_hike_counters() внутри пишет счётчики, а не
-- вместимость, и до условия WHEN такой UPDATE даже не доходит — `update of
-- capacity` смотрит на список колонок оператора.
--
-- Единственный AFTER UPDATE на hikes, так что алфавитный порядок триггеров
-- (грабли из CLAUDE.md) здесь ни на что не влияет.
drop trigger if exists hikes_fill_spots_on_capacity on hikes;
create trigger hikes_fill_spots_on_capacity
  after update of capacity on hikes
  for each row
  when (new.capacity is distinct from old.capacity)
  execute function fill_spots_on_capacity_change();

-- ------------------------------------------------------------
-- РАЗОВОЕ ЛЕЧЕНИЕ УЖЕ РАСШИРЕННЫХ ПОХОДОВ
--
-- Если вместимость подняли до этой миграции, люди так и стоят в очереди при
-- свободных местах, и сама миграция их не тронет: триггер сработает только
-- на следующую правку, которой может не быть.
--
-- Только будущие: продвигать кого-то в состоявшийся поход нельзя. Там уже
-- отмечена явка, и запись задним числом означала бы человека, которого на
-- маршруте не было, — а от явки считается членство в клубе.
-- ------------------------------------------------------------
do $$
declare
  r record;
begin
  for r in
    select id from hikes
    where status in ('draft', 'published')
      and starts_at > now()
      and waitlist_count > 0
  loop
    perform * from fill_open_spots(r.id);
    perform refresh_hike_counters(r.id);
  end loop;
end $$;
