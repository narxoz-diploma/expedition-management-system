-- «Пришёл» — четвёртое состояние отметки явки.
--
-- ============================================================
-- ЗАЧЕМ
--
-- На сборе лидер знает ровно одно: человек тут или нет. А выбрать мог
-- только из «Прошёл», «Сошёл», «Не пришёл» — то есть из трёх ответов, ни
-- один из которых в эту минуту не известен. Нажмёт он «Прошёл», потому что
-- она единственная похожа по смыслу, и mark_attendance() в ту же секунду
-- выдаст гостю членство в клубе, а после времени выхода первая же отметка
-- закроет поход. Человек, который развернётся на первом подъёме, станет
-- участником клуба ещё на парковке.
--
-- 'arrived' не делает ничего: ни счётчиков, ни членства, ни закрытия
-- похода. Это честный промежуточный факт — «вышел с группой», — и он
-- ровно то, что лидер видит своими глазами на точке сбора.
--
-- ============================================================
-- ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ
--
-- Postgres не даёт использовать новое значение enum в той же транзакции,
-- где оно добавлено. Схемные тесты применяют миграции по файлу за раз, то
-- есть каждый файл — своя транзакция: положи это рядом с функциями,
-- которые на 'arrived' ссылаются, и всё упало бы на первом же прогоне.
-- ============================================================

-- Перед 'completed', чтобы порядок значений совпадал с порядком событий:
-- пришёл → прошёл / сошёл. Сортировки по result в коде нет, так что это
-- только для человека, читающего \dT+ в редакторе.
alter type attendance_result add value if not exists 'arrived' before 'completed';
