-- Место сбора видно только тем, кто идёт.
--
-- Зачем: на точку приходили люди мимо записи и присоединялись к группе на
-- месте. Лидер узнаёт о них, когда отказывать уже поздно — все стоят у
-- автобуса, — и в маршрут уходит группа, которой нет ни в одном списке.
-- Адрес, известный только записавшимся, — единственный рычаг, который у
-- сайта для этого есть.
--
-- Время выхода при этом остаётся публичным: оно стоит в заголовке карточки,
-- в анонсе и в превью ссылки. Скрывается ровно место.
--
-- ============================================================
-- ПОЧЕМУ ЭТО МИГРАЦИЯ, А НЕ УСЛОВИЕ В ВЁРСТКЕ
--
-- Anon key лежит в клиентском бандле, а RLS отсекает строки, а не колонки:
-- поход опубликован — значит строка отдаётся целиком, вместе с адресом.
-- Условие в разметке спрятало бы блок от глаз и оставило бы данные в ответе
-- PostgREST. Это украшение, а не защита.
-- ============================================================

-- Право select выдано на таблицу целиком, а из табличного права колонку не
-- вычесть: `revoke select (meeting_point) on hikes` отвечает «no privileges
-- could be revoked» и молча ничего не делает. Поэтому право снимается
-- полностью и выдаётся обратно поколоночно.
--
-- Список колонок собирается запросом, а не переписывается сюда руками:
-- переписанный он разошёлся бы со схемой при первой же новой колонке, и
-- разошёлся бы молча — до первого запроса с прода.
--
-- ВНИМАНИЕ на будущее: с этого момента новая колонка hikes клиенту не
-- читается, пока ей отдельно не выдадут select. Тест «что видно анониму»
-- проверяет состав открытых колонок и падает, если про это забыли.
do $$
declare
  cols text;
begin
  select string_agg(quote_ident(column_name), ', ' order by ordinal_position)
    into cols
    from information_schema.columns
   where table_schema = 'public'
     and table_name = 'hikes'
     and column_name not in ('meeting_point', 'meeting_point_url');

  execute 'revoke select on hikes from anon, authenticated';
  execute format('grant select (%s) on hikes to anon, authenticated', cols);
end $$;

-- ============================================================
-- КТО ИДЁТ В ПОХОД
--
-- Отдельная функция, а не условие внутри hike_meeting_point: этим же
-- вопросом определяется доступ к расписке, и два места должны отвечать на
-- него одинаково, а не похоже.
--
-- Лист ожидания сюда НЕ входит намеренно. Это и есть те самые лишние люди у
-- автобуса: место в группе им ещё не досталось, а придут они по адресу так
-- же, как записанные. Поднимут из очереди — попадут сюда сами, отдельного
-- действия не нужно.
-- ============================================================

create or replace function is_hike_participant(p_hike_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select is_hike_leader(p_hike_id)
      or exists (
        select 1 from registrations r
         where r.hike_id = p_hike_id
           and r.user_id = auth.uid()
           and r.status = 'confirmed'
      );
$$;

-- ============================================================
-- МЕСТО СБОРА
--
-- Возвращает не только значение, но и признак доступа. Без него страница не
-- отличила бы «тебе не показываем» от «лидер не заполнил» — а это разные
-- сообщения: в первом случае человеку надо предложить записаться, во втором
-- предлагать нечего.
-- ============================================================

create or replace function hike_meeting_point(p_hike_id uuid)
returns table (visible boolean, meeting_point text, meeting_point_url text)
language sql stable security definer set search_path = public as $$
  select v.ok,
         case when v.ok then h.meeting_point end,
         case when v.ok then h.meeting_point_url end
    from hikes h
    cross join lateral (select is_hike_participant(h.id) as ok) v
   where h.id = p_hike_id;
$$;
