-- Расписка участника: два бланка на поход.
--
-- Бумага, которую человек подписывает и приносит на выход. Бланков два, и
-- различаются они не оформлением, а тем, кто подписывает: совершеннолетний
-- расписывается сам, за младшего — родитель. Показывать оба всем — значит
-- гарантированно получить часть группы с неверным бланком, поэтому нужный
-- выбирается по дате рождения из профиля.
--
-- Почему файлы у похода, а не у клуба: в бланке стоят дата и название
-- маршрута. Один общий шаблон пришлось бы дозаполнять руками каждому — то
-- есть перекладывать на участника ровно ту работу, ради которой заводится
-- поле.
--
-- ============================================================
-- КОЛОНКИ
-- ============================================================

alter table hikes
  add column waiver_adult_path text,
  add column waiver_minor_path text;

-- Право на чтение выдаётся явно: с миграции 20260812 select на hikes
-- выдан поколоночно, и новая колонка клиенту не видна, пока про неё не
-- сказали отдельно. Это тот самый случай, о котором там написано.
--
-- Сами пути не секрет: в них id похода и случайное имя файла, а доступ к
-- содержимому решает политика на storage.objects. Зато по их наличию видно,
-- что расписка на поход нужна, — и сказать об этом стоит до записи, а не
-- после.
grant select (waiver_adult_path, waiver_minor_path) on hikes to anon, authenticated;

-- ============================================================
-- БАКЕТ
--
-- Закрытый, в отличие от снимков и аватаров. Открытый бакет отдаёт файл
-- всякому, кто знает адрес, а адрес — это то, что пересылают в чат первым
-- делом. Ссылки на бланк подписываются на несколько минут и выдаются
-- сервером тем, кто идёт.
-- ============================================================

insert into storage.buckets (id, name, public)
values ('waivers', 'waivers', false)
on conflict (id) do nothing;

-- Первый сегмент пути — id похода, как и у снимков: waivers/{hike_id}/…
-- Разбираем split_part по той же причине — storage.foldername() нет в
-- PGlite, на котором гоняются схемные тесты.
create policy waivers_read on storage.objects
  for select to authenticated
  using (
    bucket_id = 'waivers'
    and is_hike_participant(split_part(name, '/', 1)::uuid)
  );

create policy waivers_write on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'waivers'
    and is_hike_leader(split_part(name, '/', 1)::uuid)
  );

create policy waivers_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'waivers'
    and is_hike_leader(split_part(name, '/', 1)::uuid)
  );
