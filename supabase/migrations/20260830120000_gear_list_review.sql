-- ------------------------------------------------------------
-- 1. «Кошки или ледоступы» → «Ледоступы»
--
-- Это были две разные вещи в одной строке. Ледоступы — микрошипы на подошву
-- против скользкой тропы: надел и пошёл. Настоящие кошки нужны там, где есть
-- куда падать, и в такой рельеф не выходят без ледоруба и умения зарубаться,
-- а ледоруба в списке нет и не было. Строка обещала новичку рельеф, для
-- которого не давала главного.
--
-- Клуб на такой рельеф не ходит (решение автора, 30 августа), поэтому слово
-- «кошки» убрано, а не дописан ледоруб.
-- ------------------------------------------------------------

update gear_items
   set name = 'Ледоступы'
 where slug = 'spikes';

-- ------------------------------------------------------------
-- 2. «Трекинговая обувь» → «Обувь с цепким протектором»
--
-- Прежнее название читалось как требование покупки, и это первое, обо что
-- спотыкается новичок: не количество строк в списке, а деньги. Абзац на
-- странице «что взять» и так успокаивал, что хватит кроссовок, — теперь с
-- ним согласен и сам пункт.
-- ------------------------------------------------------------

update gear_items
   set name = 'Обувь с цепким протектором'
 where slug = 'boots';

-- ------------------------------------------------------------
-- 3. Чего не хватало
--
-- Категории у новых пунктов расставлены не по «сложности вещи», а по тому,
-- где она начинает быть нужна:
--
-- * Перекус — первая. Голод не зависит от сложности маршрута, а «человек
--   просто устал и замёрз» на шести часах чаще всего означает, что он не ел.
--   Замечает это лидер последним.
--
-- * Головной убор и крем — первая, и одним пунктом: оба отвечают на один
--   вопрос, «прикрыт ли ты сверху». На 2000–3000 м ультрафиолет жёсткий, а
--   весной по снегу отражение снизу добирает то, что не достало сверху.
--
-- * Очки — третья, а не первая. На «Кок Жайляу» лес и луга, там они
--   удобство. Выше зоны леса — необходимость, а на снегу уже безопасность:
--   снежная слепота развивается за несколько часов и выводит человека из
--   строя на день.
--
-- * Шапка и перчатки — третья. «Тёплый слой» этого не покрывает: под ним
--   понимают куртку. На 3000 м даже в июле бывает около нуля с ветром, а
--   мёрзнут первыми голова и руки. Весит ничего, забывают чаще всего.
--
-- * Повербанк — третья. Сайт сам завязан на телефон: связь с лидером,
--   отметка явки. На холоде батарея садится вдвое быстрее.
--
-- Оговорка на будущее: половина этих вещей зависит не от сложности, а от
-- сезона. Прогулка первой категории в феврале требует больше тёплого, чем
-- маршрут третьей в июле, и категория здесь работает подпоркой вместо
-- сезона. Второй оси в модели нет, и заводить её сейчас не стали, — но если
-- однажды кто-то замёрзнет на лёгком февральском выходе, причина здесь.
-- ------------------------------------------------------------

insert into gear_items (slug, name, category, min_hike_category, sort_order) values
  ('snack',      'Перекус',                     'снаряжение',   1, 45),
  ('sunhat',     'Головной убор и крем от солнца', 'одежда',    1, 48),
  ('gloves',     'Шапка и перчатки',            'одежда',       3, 65),
  ('sunglasses', 'Очки от солнца',              'безопасность', 3, 75),
  ('powerbank',  'Повербанк',                   'снаряжение',   3, 95)
on conflict (slug) do update
   set name              = excluded.name,
       category          = excluded.category,
       min_hike_category = excluded.min_hike_category,
       sort_order        = excluded.sort_order;

