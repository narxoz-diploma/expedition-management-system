-- Поход становится прошедшим сам, когда лидер отмечает явку.
--
-- ============================================================
-- ЗАЧЕМ
--
-- Значение 'completed' лежало в hike_status с первого дня, и его не ставило
-- ни одно место: ни триггер, ни задача по расписанию, ни форма правки.
-- Сломано при этом ничего не было — всё, что должно знать про прошедший
-- поход, считает по дате: цифры клуба, вкладка «Прошедшие», «поход уже
-- прошёл» на карточке, «уже ходил» в профиле. Единственный видимый след —
-- состоявшийся поход оставался в админке зелёным «Опубликован».
--
-- Поэтому вопрос был не «чем чинить», а «что это слово должно значить».
-- «Дата прошла» вычисляется и хранения не требует. Хранить стоит другое:
-- **лидер вернулся и закрыл поход**. На этом потом естественно строятся
-- отзывы (окно «несколько дней после выхода» — после чего?) и уровни по
-- пройденному.
--
-- Отсюда способ: не кнопка, а отметка явки. Кнопку «поход состоялся» надо
-- не забыть нажать дома, а домой лидер возвращается уставшим и к сайту не
-- идёт. Явку он отмечает в поле, потому что она нужна ему самому.
-- ============================================================

create or replace function close_hike_on_attendance()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update hikes
     set status = 'completed'
   where id = new.hike_id
     and status = 'published'
     -- Выход уже наступил. Без этого условия поход закрывался бы на точке
     -- сбора: окно отметок открывается за два часа ДО выхода, а
     -- listUpcomingHikes показывает только 'published' — поход исчез бы из
     -- «Ближайших», не появившись в «Прошедших», ровно пока группа идёт.
     --
     -- Плата за условие: если лидер отметил всех до старта и больше не
     -- возвращался, поход останется опубликованным. Это ничего не ломает —
     -- см. выше, всё считается по дате, — и это честно: он его не закрыл.
     and starts_at <= now();

  return new;
end;
$$;

-- И на update тоже: mark_attendance идемпотентна и вторую отметку тому же
-- человеку пишет через on conflict do update. Первая отметка на поход
-- всегда insert, так что для закрытия хватило бы и его, но исправление
-- ошибки не должно зависеть от того, каким путём строка легла.
create trigger attendance_closes_hike
  after insert or update on attendance
  for each row execute function close_hike_on_attendance();

revoke all on function close_hike_on_attendance() from public, anon, authenticated;

