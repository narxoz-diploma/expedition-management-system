-- Снаряжение: 'can_borrow' → 'will_get'.
--
-- Старое значение подписывалось в интерфейсе как «Одолжу» и читалось двумя
-- противоположными способами: «я одолжу кому-то» и «мне одолжат». Второе
-- прочтение опаснее — оно выглядит обещанием клуба выдать снаряжение, а клуб
-- ничего не выдаёт: у лидеров нет запаса ботинок.
--
-- Заодно меняется смысл для расчёта готовности (см. src/lib/gear-readiness.ts):
-- раньше «могу одолжить» засчитывалось за наличие, и человек с пустым рюкзаком
-- получал зелёную цифру готовности. Теперь «достану» — это «пока нет».
--
-- Переименование значения enum, а не новый тип: строки в user_gear
-- переезжают сами, переписывать данные не нужно.
alter type gear_ownership rename value 'can_borrow' to 'will_get';
