-- «Где уже был» — опыт человека до клуба, своими словами.
--
-- Пройденные с клубом походы сайт знает и так, они лежат в registrations и
-- показываются в профиле. Чего он не знает — что человек ходил до нас: на
-- Фурманова со школой, на Букреева с отцом, в Заилийском вообще ни разу.
-- Ровно этого не хватает лидеру, когда на поход записывается незнакомый
-- новичок, и вывести это из базы неоткуда.
--
-- Свободный текст, а не список галочками: справочник вершин пришлось бы
-- вести, он устарел бы к первому же нестандартному ответу, а лидеру нужен не
-- разбор по пунктам, а понимание, с кем он идёт.
--
-- Чего здесь намеренно НЕТ: публичности. По PRD клуб не заводит общий
-- рейтинг по километрам и вершинам — он толкает людей на маршруты не по
-- силам. Поле видно самому человеку и лидеру его похода, и всё: политика
-- profiles_select уже описывает ровно этот круг, менять её не нужно.

alter table profiles
  add column visited_places text;

-- Ограничение на длину — не про экономию места, а про то, что это поле
-- читают с телефона в списке из двадцати человек. Абзац читают, страницу
-- пролистывают.
alter table profiles
  add constraint profiles_visited_places_length
  check (visited_places is null or char_length(visited_places) <= 1000);
